#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const rawPath = path.join(root, "assets", "strokes", "graphicsZhHant-subset.jsonl");
const outputPath = path.join(root, "stroke-data.js");
const subsetNotice = {
  _strokeSubsetNotice: {
    modified: "2026-09-22",
    how: "Selected 25 character records from the pinned animCJK graphicsZhHant.txt; stroke paths and medians are unchanged.",
    sourceCopyright: "AnimCJK 2016-2026 FM&SH; Arphic 1999",
    license: "Arphic Public License",
    licenseFile: "assets/strokes/licenses/ARPHICPL.TXT",
    sourceNoticeFile: "assets/strokes/licenses/COPYING.txt",
  },
};

const lessons = [
  { sourceLesson: "第一課：拍拍手", characters: [..."拍手左右你他也上下"] },
  { sourceLesson: "第二課：這是誰的?", characters: [..."這是誰的我分好了啊多個"] },
  { sourceLesson: "第三課：秋千", characters: [..."秋千和玩高"] },
];

const selection = lessons.flatMap(({ sourceLesson, characters }) =>
  characters.map((char) => ({ char, sourceLesson })),
);

function parseJsonLines(file, allowSubsetNotice = false) {
  const lines = fs
    .readFileSync(file, "utf8")
    .split(/\r?\n/)
    .filter(Boolean);
  if (allowSubsetNotice) {
    const header = JSON.parse(lines.shift() || "null");
    if (JSON.stringify(header) !== JSON.stringify(subsetNotice)) {
      throw new Error(`Missing or outdated modification notice in ${file}`);
    }
  }
  return lines.map((line, index) => {
      try {
        return JSON.parse(line);
      } catch (error) {
        throw new Error(`Invalid JSON on ${file}:${index + 1 + Number(allowSubsetNotice)}: ${error.message}`);
      }
    });
}

function writeSubset(entries) {
  fs.mkdirSync(path.dirname(rawPath), { recursive: true });
  fs.writeFileSync(rawPath, `${[subsetNotice, ...entries].map(JSON.stringify).join("\n")}\n`, "utf8");
}

function extractSubset(sourcePath) {
  const source = new Map(parseJsonLines(sourcePath).map((entry) => [entry.character, entry]));
  const missing = selection.filter(({ char }) => !source.has(char)).map(({ char }) => char);
  if (missing.length) throw new Error(`Missing selected ZhHant characters: ${missing.join(" ")}`);
  writeSubset(selection.map(({ char }) => source.get(char)));
}

if (process.argv[2] === "--extract") {
  if (!process.argv[3]) throw new Error("Usage: node scripts/build-stroke-data.cjs --extract <graphicsZhHant.txt>");
  extractSubset(path.resolve(process.argv[3]));
}

const raw = new Map(parseJsonLines(rawPath, true).map((entry) => [entry.character, entry]));
const characters = selection.map(({ char, sourceLesson }) => {
  const entry = raw.get(char);
  if (!entry) throw new Error(`Subset is missing selected character: ${char}`);
  if (!Array.isArray(entry.strokes) || !Array.isArray(entry.medians) || entry.strokes.length !== entry.medians.length) {
    throw new Error(`Invalid stroke/median data for ${char}`);
  }
  return { char, strokes: entry.strokes, medians: entry.medians, sourceLesson };
});

const payload = { characters };
const banner = `// Generated by scripts/build-stroke-data.cjs. See STROKE_SOURCES.md.\n// Modified 2026-09-22: selected 25 animCJK ZhHant characters and wrapped them for browser/CommonJS use; path geometry and medians unchanged.\n// Source copyright: AnimCJK 2016-2026 FM&SH; Arphic 1999. Stroke data: Arphic Public License.\n// Full license: assets/strokes/licenses/ARPHICPL.TXT; upstream notice: assets/strokes/licenses/COPYING.txt.\n`;
const body = `(function (root, data) {\n  if (typeof module === "object" && module.exports) module.exports = data;\n  if (root) root.STROKE_DATA = data;\n})(typeof window !== "undefined" ? window : globalThis, ${JSON.stringify(payload, null, 2)});\n`;
fs.writeFileSync(outputPath, banner + body, "utf8");
console.log(`Wrote ${characters.length} characters to ${outputPath}`);
